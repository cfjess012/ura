import { chromium } from "@playwright/test";
const b = await chromium.launch();
const p = await (await b.newContext()).newPage();
p.setDefaultTimeout(10000);
await p.goto("http://localhost:3100/");
await p.getByRole("button", { name: /Priya Sharma/ }).click();
await p.getByRole("textbox").first().fill("Verifier walk A");
await p.getByRole("button", { name: /Start assessment/ }).click();
await p.waitForLoadState("networkidle");
console.log("URL:", p.url());
console.log((await p.locator("body").innerText()).slice(0, 3000));
await p.screenshot({ path: "/tmp/v-intake1.png", fullPage: true });
await b.close();
